/**
 * Build src/data/sky.json: bright stars, their common names, and
 * constellation lines and labels. The stars do not change, so the output is
 * committed and this only needs re-running to change what goes in.
 *
 *     npm run stars
 *
 * Sources:
 * - Yale Bright Star Catalogue, 5th revised edition (Hoffleit & Warren
 *   1991), via CDS VizieR V/50. J2000 positions; proper motion is ignored
 *   (under 1′ for every star here over this century).
 * - Constellation lines and names: d3-celestial by Olaf Frohn, BSD-3-Clause.
 */
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gunzipSync, strFromU8 } from 'fflate'
import { parseBsc5, STAR_NAMES, type Bsc5Star } from './lib/stars.ts'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const CACHE = join(ROOT, '.cache', 'sky')
const OUT = join(ROOT, 'src', 'data', 'sky.json')
const MAG_LIMIT = 5.5

// Pinned to the last commit (Jul 2022) so a rebuild reads the same lines.
const D3 = 'https://cdn.jsdelivr.net/gh/ofrohn/d3-celestial@7e720a3de062059d4c5400a379146a601d9010e0/data'

async function cached(url: string, name: string): Promise<Uint8Array> {
  const path = join(CACHE, name)
  try {
    await stat(path)
    return new Uint8Array(await readFile(path))
  } catch {
    const res = await fetch(url, { signal: AbortSignal.timeout(60_000) })
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`)
    const body = new Uint8Array(await res.arrayBuffer())
    await mkdir(CACHE, { recursive: true })
    await writeFile(path, body)
    return body
  }
}

interface GeoFeature<G> {
  id: string
  properties: { name: string }
  geometry: G
}

const round = (x: number, d: number) => Math.round(x * 10 ** d) / 10 ** d
/** d3-celestial stores RA as a longitude in (−180, 180]. */
const ra360 = (lon: number) => (lon < 0 ? lon + 360 : lon)

async function main() {
  const bsc = parseBsc5(strFromU8(gunzipSync(await cached('https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz', 'bsc5.dat.gz'))))
  const stars = bsc.filter((s) => s.vmag <= MAG_LIMIT).sort((a, b) => a.vmag - b.vmag)

  // Each name goes to the brightest star with that designation (Mizar's
  // "Zet UMa" covers both components, for instance). A name matching
  // nothing means a typo in STAR_NAMES, so stop.
  const names: Record<number, string> = {}
  for (const [desig, name] of Object.entries(STAR_NAMES)) {
    const i = stars.findIndex((s: Bsc5Star) => s.desig === desig)
    if (i < 0) throw new Error(`No star brighter than ${MAG_LIMIT} is designated "${desig}" (for ${name})`)
    names[i] = name
  }

  const lines = JSON.parse(strFromU8(await cached(`${D3}/constellations.lines.json`, 'constellations.lines.json'))) as {
    features: GeoFeature<{ coordinates: [number, number][][] }>[]
  }
  const labels = JSON.parse(strFromU8(await cached(`${D3}/constellations.json`, 'constellations.json'))) as {
    features: GeoFeature<{ coordinates: [number, number] }>[]
  }
  const labelById = new Map(labels.features.map((f) => [f.id, f]))
  const constellations = lines.features.map((f) => {
    const label = labelById.get(f.id)
    if (!label) throw new Error(`No label for constellation ${f.id}`)
    return {
      id: f.id,
      name: label.properties.name,
      label: [round(ra360(label.geometry.coordinates[0]), 2), round(label.geometry.coordinates[1], 2)],
      lines: f.geometry.coordinates.map((line) => line.map(([lon, lat]) => [round(ra360(lon), 3), round(lat, 3)])),
    }
  })

  const sky = {
    note: 'Generated by scripts/build-stars.ts. Stars: Yale BSC5 (VizieR V/50), J2000. Constellations: d3-celestial (BSD-3-Clause, Olaf Frohn).',
    magLimit: MAG_LIMIT,
    /** [RA°, Dec°, V mag, B−V] per star, brightest first. */
    stars: stars.map((s) => [round(s.ra, 4), round(s.dec, 4), s.vmag, s.bv]),
    names,
    constellations,
  }
  await writeFile(OUT, JSON.stringify(sky) + '\n')
  console.log(`Wrote ${OUT}: ${stars.length} stars, ${Object.keys(names).length} named, ${constellations.length} constellations`)
}

main().catch((e: unknown) => {
  console.error(e)
  process.exit(1)
})
